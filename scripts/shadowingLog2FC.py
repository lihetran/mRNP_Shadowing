def getReferenceFreq(refDict):
    """
    refDict is of the format
    {readID:{position:edit}}
    For every position, will compute a frequency of edit and a frequency of 
    nonedit, and output it as:
    {position:(freq0,freq1)}
    """
    aa=collections.defaultdict(list)
    for readID,positionDict in refDict.items():
        for position,editStatus in positionDict.items():
            # ic(position,editStatus)
            aa[position].append(editStatus)
    ##aa is of the format {position:[0,1,1,0,0,0,1,1,1,],...}
    bb={}
    for position,editList in aa.items():
        freq0=editList.count(0)/len(editList)
        freq1=editList.count(1)/len(editList)
        bb[position]=(freq0,freq1)
    ##
    return bb

def smoothing(referenceFreq, ntWindow, start, end):
    """
    Takes a dictionary of reference frequencies and smooths it over a window. 
 
    referenceFreq is of the format {bc: {position:(freq0,freq1)}}
    ntWindow is an integer, the size of the window to smooth over.
    Returns a smoothed dictionary of the same format.
    """
    smoothedFreq = collections.defaultdict(lambda: collections.defaultdict(list))
    for bc, freqDict in referenceFreq.items():
        for position, (freq0, freq1) in freqDict.items():
            if start <= position < end:
                # Calculate the range for smoothing
                start_pos = max(start, position - ntWindow // 2)
                end_pos = min(end, position + ntWindow // 2)
                # Collect frequencies in the window
                window_freqs = [freqDict.get(pos, (0, 0)) for pos in range(start_pos, end_pos)]
                # Calculate smoothed frequencies
                smoothed_freq0 = sum(freq[0] for freq in window_freqs) / len(window_freqs)
                smoothed_freq1 = sum(freq[1] for freq in window_freqs) / len(window_freqs)
                smoothedFreq[bc][position] = (smoothed_freq0, smoothed_freq1)

    return smoothedFreq


def computeLog2FC(editFreq_dict1, editFreq_dict2):
    '''
    Returns a dictionary of log2 fold changes between two dictionaries of edit frequencies.

    editFreq_dict1 and editFreq_dict2 are dictionaries of the form:
    {bc: {position: (freq0, freq1)}}
    where freq0 is the frequency of non-edit and freq1 is the frequency of edit.
    
    The output is a dictionary of the form:
    {bc: {position: log2fc_nonedit, log2fc_edit}}
    where log2fc_nonedit = log2(freq0_2 / freq0_1) and log2fc_edit = log2(freq1_2 / freq1_1).
    '''
    print('Computing log2 fold change...')
    log2fc_dict = collections.defaultdict(lambda: collections.defaultdict(dict))
    
    for bc in editFreq_dict1.keys():
        for position in editFreq_dict1[bc].keys() | editFreq_dict2[bc].keys():
            freq1 = editFreq_dict1[bc].get(position, (0, 0))
            freq2 = editFreq_dict2[bc].get(position, (0, 0))
            if freq1[1] > 0 and freq2[1] > 0:
                log2fc_nonedit = math.log2((freq1[0] / freq1[1]) / (freq2[0] / freq2[1]))
                log2fc_edit = math.log2((freq1[1] / freq1[0]) / (freq2[1] / freq2[0]))
                log2fc_dict[bc][position] = (log2fc_nonedit, log2fc_edit)

    return log2fc_dict

def computeLog2FCFromBarcode(editFreq_dict, barcode):
    """
    Computes the log2 fold change of all barcodes editing against background barcode.

    """
    print('Computing log2 fold change for barcode %s...' % barcode)
    log2fc_dict = collections.defaultdict(dict)
    background_freq = editFreq_dict[barcode]

    for bc, freqDict in editFreq_dict.items():
        for position, (freq0, freq1) in freqDict.items():
            if position in background_freq:
                bg_freq0, bg_freq1 = background_freq[position]
                if bg_freq1 > 0 and freq1 > 0:
                    log2fc_nonedit = math.log2((bg_freq0 / bg_freq1) / (freq0 / freq1))
                    log2fc_edit = math.log2((bg_freq1 / bg_freq0) / (freq1 / freq0))
                    log2fc_dict[bc][position] = (log2fc_nonedit, log2fc_edit)

    return log2fc_dict

def getMetaReadPerBarcode(log2fc_dict):
    """
    log2fc_dict is a dictionary of the form {bc: {position: log2fc_nonedit, log2fc_edit}}.
    For all readIDs w/in one bc, will get summary metrics of the log2fc for each
    position, returning a dict of the format:
    {bc:[(x,quartile25,median,quartile75),...]}
    """
    print('#####\nMaking metaRead of log2fc...\n#####')
    ##
    aa=collections.defaultdict(lambda:collections.defaultdict(list))
    for bc,positionDict in log2fc_dict.items():
        for position,log2fc in positionDict.items():
            aa[bc][position].append(log2fc)
    ##
    ##aa is of the format:
    ##{bc:position:[value list of probs]}
    bb={}
    for bc,positionDict in aa.items():
        ##initialize the dict
        bb[bc]=[]
        ##
        tempList=[entry for entry in positionDict.keys()]
        tempList.sort()
        ##
        for position in tempList:
            freqVals=positionDict[position]
            bb[bc].append((position, freqVals[0][0], freqVals[0][1]))
    ##
    print('Did top/bottom deciles rather than quartiles...')
    return bb


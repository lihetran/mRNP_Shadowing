def parseBCFile(bcFile):
    '''
    Barcode file is a tab separated file with barcodes mapped to sample names.
    '''
    bc_dict = {}
    with open(bcFile, 'r') as f:
        for line in f:
            line = line.rstrip().split()

            if len(line) == 2:
                barcode, sample_name = line
                bc_dict[barcode] = sample_name
    return bc_dict


